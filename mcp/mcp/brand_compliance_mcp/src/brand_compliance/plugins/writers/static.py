"""Writer for static pages: one brand ``<style>`` block plus element annotations."""

import logging
from collections import defaultdict
from typing import Final

from lxml import etree
from lxml.html import HtmlElement

from brand_compliance.core.markers import (
    ANNOTATION_ATTRIBUTES,
    FONT_LINK_ATTRIBUTE,
    FORCE_ATTRIBUTE,
    ROLE_ATTRIBUTE,
    STYLE_ID,
    SURFACE_ATTRIBUTE,
)
from brand_compliance.models.artifact import ArtifactModel, ArtifactType
from brand_compliance.models.change import Change
from brand_compliance.plugins.appliers.font import FONT_SOURCE_PROPERTY
from brand_compliance.plugins.writers.base import add_font_links, ensure_head

logger = logging.getLogger(__name__)

UNMAPPED_ROLE: Final = "unmapped"
_PREFIX: Final = f"html:not(#{STYLE_ID})"  # the id inside :not() boosts specificity
_LIGHT_MODE_ONLY: Final = (
    "@media (prefers-color-scheme: light), (prefers-color-scheme: no-preference)"
)
_HEADER: Final = (
    "/* Generated by brand-compliance-mcp. Edit the brand guide, not this block. */"
)

_Declarations = dict[str, tuple[str, bool]]


class StylesheetWriter:
    """Writes changes as brand rules that win over the page's own styles."""

    name = "stylesheet"
    artifact_type = ArtifactType.STATIC

    def write(self, changes: list[Change], artifact: ArtifactModel) -> ArtifactModel:
        """Add the brand block (and font link) to the artifact's tree."""
        variable_changes = [c for c in changes if c.property.startswith("--")]
        style_changes = [
            c
            for c in changes
            if c.property != FONT_SOURCE_PROPERTY and not c.property.startswith("--")
        ]
        font_urls = [c.after for c in changes if c.property == FONT_SOURCE_PROPERTY]
        if not style_changes and not font_urls and not variable_changes:
            return artifact  # nothing new: keep whatever brand output is there
        head = ensure_head(artifact.tree)
        _remove_previous(head)
        _clear_annotations(artifact.tree)
        blocks = self._annotate(style_changes, artifact)
        add_font_links(head, font_urls)
        if blocks or variable_changes:
            css = (
                _render(blocks, _prefix(artifact), _wrap_in_light_mode(artifact))
                if blocks
                else f"\n{_HEADER}"
            )
            css += _render_variables(variable_changes, artifact)
            style = etree.SubElement(head, "style", id=STYLE_ID)
            style.text = css
        if artifact.styles and artifact.styles.dark_variants and blocks:
            artifact.notes.append(
                "The page has dark-theme styles; brand styles apply only in light "
                "mode, so the dark theme keeps its original look"
            )
        if variable_changes:
            artifact.notes.append(
                f"Pointed {len({c.property for c in variable_changes})} of the "
                "page's colour variable(s) at the brand palette"
            )
        artifact.notes.append(
            f"Marked {len({c.location for c in style_changes})} element(s) with "
            f"{ROLE_ATTRIBUTE} so brand rules target them exactly"
        )
        return artifact

    @staticmethod
    def _annotate(
        changes: list[Change], artifact: ArtifactModel
    ) -> dict[tuple[str, str | None, str | None], _Declarations]:
        """Mark elements and group edits as ``(role, surface, forced property)``.

        A change that must override an inline style is forced only on its own
        element, through ``data-brand-force``, never for the whole role.
        """
        blocks: dict[tuple[str, str | None, str | None], _Declarations] = defaultdict(
            dict
        )
        for change in changes:
            element = artifact.tree.xpath(change.location)[0]
            role = artifact.roles.get(change.location, UNMAPPED_ROLE)
            element.set(ROLE_ATTRIBUTE, role)
            if change.surface:
                element.set(SURFACE_ATTRIBUTE, change.surface)
            forced = change.property if change.important else None
            if forced:
                known = set((element.get(FORCE_ATTRIBUTE) or "").split())
                element.set(FORCE_ATTRIBUTE, " ".join(sorted(known | {forced})))
            blocks[(role, change.surface, forced)][change.property] = (
                change.after,
                change.important,
            )
        return blocks


def _clear_annotations(root: HtmlElement) -> None:
    """Remove annotations left by an earlier run so only current ones remain."""
    for element in root.iter():
        for attribute in ANNOTATION_ATTRIBUTES:
            if isinstance(element.tag, str) and attribute in element.attrib:
                del element.attrib[attribute]


def _remove_previous(head: HtmlElement) -> None:
    """Drop an earlier brand block and font link so re-running stays stable."""
    for element in list(head):
        if element.get("id") == STYLE_ID or element.get(FONT_LINK_ATTRIBUTE):
            head.remove(element)


def _wrap_in_light_mode(artifact: ArtifactModel) -> bool:
    return bool(artifact.styles and artifact.styles.dark_variants)


def _prefix(artifact: ArtifactModel) -> str:
    """Selector prefix: an id boost, and no match while a dark theme is switched on."""
    toggles = sorted(artifact.styles.dark_selectors) if artifact.styles else []
    return _PREFIX + "".join(f":not({selector})" for selector in toggles)


def _variable_block(selector: str, declarations: dict[str, str]) -> str:
    body = "\n".join(
        f"  {name}: {value};" for name, value in sorted(declarations.items())
    )
    return f"{selector} {{\n{body}\n}}"


def _render_variables(changes: list[Change], artifact: ArtifactModel) -> str:
    """Brand colour variables on the root, one block per surface.

    Light values come first and are kept out of dark mode the same way role
    rules are; dark values go in the page's own dark scopes.
    """
    light = {c.property: c.after for c in changes if c.surface != "dark"}
    dark = {c.property: c.after for c in changes if c.surface == "dark"}
    parts: list[str] = []
    if light:
        text = _variable_block(_prefix(artifact), light)
        if _wrap_in_light_mode(artifact):
            text = f"{_LIGHT_MODE_ONLY} {{\n{text}\n}}"
        parts.append(text)
    if dark:
        toggles = sorted(artifact.styles.dark_selectors) if artifact.styles else []
        explicit = [f"html{t}:not(#{STYLE_ID})" for t in toggles]
        # follow the system setting unless the page forces light
        system = f"html:not(#{STYLE_ID})" + (
            ':not([data-theme="light"])' if toggles else ""
        )
        parts.append(
            "@media (prefers-color-scheme: dark) {\n"
            + _variable_block(system, dark)
            + "\n}"
        )
        parts.extend(_variable_block(selector, dark) for selector in explicit)
    return ("\n" + "\n".join(parts) + "\n") if parts else ""


def _render(
    blocks: dict[tuple[str, str | None, str | None], _Declarations],
    prefix: str,
    wrap: bool,
) -> str:
    rules: list[str] = []
    ordered = sorted(blocks.items(), key=lambda kv: tuple(part or "" for part in kv[0]))
    for (role, surface, forced), declarations in ordered:
        selector = f'{prefix} [{ROLE_ATTRIBUTE}="{role}"]'
        if surface:
            selector += f'[{SURFACE_ATTRIBUTE}="{surface}"]'
        if forced:
            selector += f'[{FORCE_ATTRIBUTE}~="{forced}"]'
        body = "\n".join(
            f"  {prop}: {value}{' !important' if important else ''};"
            for prop, (value, important) in sorted(declarations.items())
        )
        rules.append(f"{selector} {{\n{body}\n}}")
    text = "\n".join(rules)
    if wrap:
        text = f"{_LIGHT_MODE_ONLY} {{\n{text}\n}}"
    return f"\n{_HEADER}\n{text}\n"
